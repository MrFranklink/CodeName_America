DECLARE @FixedCount INT;

UPDATE FixedDepositAccount
SET MaturityAmount = ROUND(
    Amount * POWER(
        (1 + FD_ROI / 100.0),
     DATEDIFF(MONTH, StartDate, EndDate) / 12.0
    ),
    2
)
WHERE MaturityAmount IS NULL OR MaturityAmount = 0;

SET @FixedCount = @@ROWCOUNT;

IF @FixedCount > 0
BEGIN
    PRINT '? Fixed ' + CAST(@FixedCount AS VARCHAR) + ' FD account(s)';
    
    -- Show updated values
    SELECT 
     FDAccountID,
        Amount AS 'Principal',
   FD_ROI AS 'Rate%',
        MaturityAmount,
        (MaturityAmount - Amount) AS 'Interest'
    FROM FixedDepositAccount
    WHERE FDAccountID IN (
        SELECT TOP 5 FDAccountID 
        FROM FixedDepositAccount 
        ORDER BY FDAccountID DESC
    );
END
ELSE
BEGIN
    PRINT '? All FD accounts already have MaturityAmount';
END

PRINT '';

-- ???????????????????????????????????????????????????????????????
-- FIX 2: Add FD_MATURITY to transaction type constraint
-- ???????????????????????????????????????????????????????????????
