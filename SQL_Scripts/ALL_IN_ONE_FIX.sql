SELECT @ValidMaturity = COUNT(*) FROM FixedDepositAccount WHERE MaturityAmount > 0;
SELECT @InvalidMaturity = COUNT(*) FROM FixedDepositAccount WHERE MaturityAmount IS NULL OR MaturityAmount = 0;

PRINT '';
