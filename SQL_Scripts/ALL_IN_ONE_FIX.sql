WHERE TABLE_NAME = 'SavingsAccount' 
  AND COLUMN_NAME = 'Balance';

PRINT '  Current: DECIMAL(' + CAST(@CurrentPrecision AS VARCHAR) + ',' + CAST(@CurrentScale AS VARCHAR) + ')';

-- Increase precision to handle large balances
ALTER TABLE SavingsAccount
ALTER COLUMN Balance DECIMAL(18,4);

